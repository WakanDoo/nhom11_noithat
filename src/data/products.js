export function getProductById(id) {
  const rawId = String(id ?? "");
  let decodedId = rawId;

  try {
    decodedId = decodeURIComponent(rawId);
  } catch {
    decodedId = rawId;
  }

  return products.find(
    (product) => product.id === rawId || product.id === decodedId
  );
}
